"""Generate the firmware's src/*_gen.* files from tools/icons_def.py, lang/*.json,
assets/icons3d/*.qoi and web/index.html.

Runs automatically before every PlatformIO build (extra_scripts = pre:tools/gen_assets.py),
can also be run by hand: python3 tools/gen_assets.py

Generated headers only use `inline constexpr` (C++17) data, so a table included from
several .cpp files is still linked into flash once. The big colour-icon pixel arrays go
into their own translation unit, src/icons_img_gen.cpp (not committed, rebuilt from the
committed .qoi files on every build; pure Python, no Pillow needed).
"""
import base64, json, os, sys

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

sys.path.insert(0, os.path.join(ROOT, "tools"))
from icons_def import ICONS, LEGACY_IDS, LAYOUTS, FONTS, BITMAP_DIR, BITMAP_SIZE  # noqa: E402
import struct  # noqa: E402
from i18n_def import LANGS, DEFAULT_LANG, PORTAL_WM, PORTAL_WORDS, resolved, check  # noqa: E402


def hex2int(h):
    return int(h.lstrip("#"), 16)


def write_if_changed(path, text):
    if os.path.exists(path) and open(path, encoding="utf-8").read() == text:
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("gen_assets: wrote", os.path.relpath(path, ROOT))


def bitmap_path(key):
    return os.path.join(ROOT, BITMAP_DIR, key + ".qoi")


def bitmap_bytes(key):
    p = bitmap_path(key)
    if not os.path.exists(p):
        raise SystemExit("gen_assets: %s missing - run: python3 tools/fetch_icons.py" % os.path.relpath(p, ROOT))
    data = open(p, "rb").read()
    w, h = int.from_bytes(data[4:8], "big"), int.from_bytes(data[8:12], "big")
    if data[:4] != b"qoif" or w != BITMAP_SIZE or h != BITMAP_SIZE:
        raise SystemExit("gen_assets: %s is not a %dx%d QOI image - run tools/fetch_icons.py --force" % (p, BITMAP_SIZE, BITMAP_SIZE))
    return data


def cident(key):
    return key.upper()


def gen_icons_h():
    out = ["// AUTO-GENERATED by tools/gen_assets.py from tools/icons_def.py - do not edit", "#pragma once",
           "#include <stdint.h>", ""]
    out.append("// Colour icons: QOI images (%dx%d RGBA), defined in icons_img_gen.cpp" % (BITMAP_SIZE, BITMAP_SIZE))
    out.append("static constexpr int BITMAP_SIZE = %d;" % BITMAP_SIZE)
    for key in ICONS:
        out.append("extern const uint8_t ICON_IMG_%s[%d];" % (cident(key), len(bitmap_bytes(key))))
    out.append("")
    out.append("// Default slot colours: bg = background, tx = label and clock text.")
    out.append("// sleep = night icon (sleep time for the eyes screensaver)")
    out.append("struct IconDef { const char *id; const uint8_t *img; uint32_t img_len; uint32_t bg, tx; bool sleep; };")
    out.append("inline constexpr IconDef ICON_DEFS[] = {")
    for key, v in ICONS.items():
        d = v["defaults"]
        out.append('  {"%s", ICON_IMG_%s, %d, 0x%06X, 0x%06X, %s},' % (
            key, cident(key), len(bitmap_bytes(key)), hex2int(d["bg"]), hex2int(d["tx"]),
            "true" if v.get("sleep") else "false"))
    out.append("};")
    out.append("static constexpr int ICON_COUNT = %d;" % len(ICONS))
    out.append("")
    out.append("// Icon ids used by firmware before 1.1.1 (vector icons) -> current id, for old configs.")
    out.append("struct IconAlias { const char *from, *to; };")
    out.append("inline constexpr IconAlias ICON_ALIASES[] = {%s};" % ", ".join(
        '{"%s", "%s"}' % (k, v) for k, v in LEGACY_IDS.items()))
    out.append("")
    out.append("// Round-screen layouts: icon x, y, size; label_y; clock_y (-1 = not shown)")
    out.append("struct ScreenLayout { int16_t ix, iy, isz, label_y, clock_y; };")
    for k, v in LAYOUTS.items():
        out.append("inline constexpr ScreenLayout LAYOUT_%s = {%d, %d, %d, %d, %d};" % (
            k.upper(), *v["icon"], v.get("label_y", -1), v.get("clock_y", -1)))
    return "\n".join(out) + "\n"


def gen_icons_img_cpp():
    out = ["// AUTO-GENERATED by tools/gen_assets.py from %s/*.qoi - do not edit, not committed" % BITMAP_DIR,
           "// Fluent Emoji 3D (c) Microsoft Corporation, MIT License - see THIRD_PARTY_NOTICES.md",
           '#include "icons_gen.h"', ""]
    for key in ICONS:
        data = bitmap_bytes(key)
        out.append("const uint8_t ICON_IMG_%s[%d] = {" % (cident(key), len(data)))
        for i in range(0, len(data), 32):
            out.append(",".join(str(b) for b in data[i:i + 32]) + ",")
        out.append("};")
    return "\n".join(out) + "\n"


def icons_js(with_data=False):
    icons = {}
    for key, v in ICONS.items():
        icons[key] = {"defaults": v["defaults"]}
        if with_data:  # standalone preview page only; the device serves /icons/<id>.qoi
            icons[key]["data"] = base64.b64encode(bitmap_bytes(key)).decode()
    return json.dumps(icons, ensure_ascii=False, separators=(",", ":"))


def gen_web_html(with_data=False):
    html = open(os.path.join(ROOT, "web", "index.html"), encoding="utf-8").read()
    html = html.replace("/*@ICONS@*/null", icons_js(with_data))
    html = html.replace("/*@LAYOUTS@*/null", json.dumps(LAYOUTS, separators=(",", ":")))
    i18n = {c: dict(resolved(c, "web"), _name=L["name"], _labels=resolved(c, "device")) for c, L in LANGS.items()}
    html = html.replace("/*@I18N@*/null", json.dumps(i18n, ensure_ascii=False, separators=(",", ":")))
    html = html.replace("/*@DEFAULT_LANG@*/null", json.dumps(DEFAULT_LANG))
    html = html.replace("/*@VERSION@*/null", json.dumps(fw_version()))
    with open(os.path.join(ROOT, "web", "favicon.png"), "rb") as f:
        html = html.replace("/*@FAVICON@*/", base64.b64encode(f.read()).decode())
    return html


def fw_version():
    for line in open(os.path.join(ROOT, "src", "version.h"), encoding="utf-8"):
        if line.startswith("#define KIDO_VERSION"):
            return line.split('"')[1]
    raise SystemExit("gen_assets: KIDO_VERSION not found in src/version.h")


def gen_web_h():
    """The page is stored gzip-compressed (about 4x smaller); the server sends it with
    Content-Encoding: gzip, which every browser understands."""
    import gzip
    gz = gzip.compress(gen_web_html().encode("utf-8"), compresslevel=9, mtime=0)
    rows = [", ".join("0x%02X" % b for b in gz[i:i + 20]) for i in range(0, len(gz), 20)]
    return ("// AUTO-GENERATED by tools/gen_assets.py from web/index.html - do not edit\n#pragma once\n"
            "#include <pgmspace.h>\n#include <stdint.h>\n// gzip-compressed web UI page\n"
            "inline constexpr uint8_t INDEX_HTML_GZ[] PROGMEM = {\n  " + ",\n  ".join(rows) + "\n};\n"
            "inline constexpr unsigned INDEX_HTML_GZ_LEN = %d;\n" % len(gz))


def gen_preview_html():
    """Standalone copy of the UI for desktop preview (demo data when /api is missing, icons inlined)."""
    return gen_web_html(with_data=True)


def gen_fonts_h():
    ttf = os.path.join(ROOT, "tools", "fonts", "DejaVuSans-Bold.ttf")
    out = ["// AUTO-GENERATED by tools/gen_assets.py (DejaVu Sans Bold, see tools/fonts/DejaVu-LICENSE.txt)",
           "#pragma once", "#include <stdint.h>", "#include <pgmspace.h>", ""]
    for name, f in FONTS.items():
        from vlw import make_vlw
        data = make_vlw(ttf, f["px"], f["chars"])
        out.append("// %d px, %d glyphs, %d bytes" % (f["px"], len(set(f["chars"])), len(data)))
        out.append("inline constexpr uint8_t FONT_%s[] PROGMEM = {" % name.upper())
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
    return "\n".join(out) + "\n"


