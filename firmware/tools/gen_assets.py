def gen_i18n_h():
    keys = list(LANGS["en"]["device"].keys())
    codes = list(LANGS.keys())
    out = ["// AUTO-GENERATED by tools/gen_assets.py from lang/*.json - do not edit", "#pragma once", "",
           "enum StrId {"] + ["  S_%s," % k.upper() for k in keys] + ["  S_COUNT", "};", "",
           "static constexpr int LANG_COUNT = %d;" % len(codes),
           "static constexpr int LANG_DEFAULT = %d;  // %s" % (codes.index(DEFAULT_LANG), DEFAULT_LANG),
           "static constexpr int LANG_EN = %d;" % codes.index("en"),
           "inline constexpr const char *LANG_CODES[LANG_COUNT] = {%s};" % ", ".join('"%s"' % c for c in codes),
           "inline constexpr const char *LANG_NAMES[LANG_COUNT] = {%s};" % ", ".join(
               json.dumps(LANGS[c]["name"], ensure_ascii=False) for c in codes),
           "inline constexpr const char *STRINGS[LANG_COUNT][S_COUNT] = {"]
    for c in codes:
        d = resolved(c, "device")
        out.append("  { // %s" % c)
        out += ["    %s," % json.dumps(d[k], ensure_ascii=False) for k in keys]
        out.append("  },")
    out.append("};")
    out.append("")
    out.append("// Wi-Fi setup portal (see PORTAL_WM in tools/i18n_def.py): per language a JSON object")
    out.append("// t = WiFiManager English text -> translation, w = single words, k = own strings.")
    out.append("inline constexpr const char *PORTAL_I18N[LANG_COUNT] = {")
    for c in codes:
        out.append("  R\"json(%s)json\"," % portal_json(c))
    out.append("};")
    labels = []
    for c in codes:
        lbl = resolved(c, "portal")["language"]
        if lbl not in labels:
            labels.append(lbl)
    out.append("// Shown above the language picker, in every language")
    out.append("inline constexpr const char PORTAL_LANG_LABEL[] = %s;" % json.dumps(" / ".join(labels), ensure_ascii=False))
    return "\n".join(out) + "\n"


def portal_json(code):
    P = resolved(code, "portal")
    t = {src: P[k] for k, src in PORTAL_WM.items() if P[k] != src}
    w = {src: P[k] for k, src in PORTAL_WORDS.items() if P[k] != src}
    k = {key: v for key, v in P.items() if key not in PORTAL_WM and key not in PORTAL_WORDS}
    js = json.dumps({"lang": code, "t": t, "w": w, "k": k}, ensure_ascii=False, separators=(",", ":"))
    js = js.replace("</", "<\\/")  # safe inside <script>
    assert ")json" not in js
    return js


